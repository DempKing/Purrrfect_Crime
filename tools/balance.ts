// The balance report: for every level, the solver's flawless route against its par, its XP and loot; then how
// Leo's level and Catnip add up over one flawless run through the story, against what the skills and the
// lair cost. With --apply, sets each level's par from its route. Usage: npm run balance [-- --apply]
import { readFileSync, writeFileSync } from 'node:fs';
import { ALL_LEVELS } from '../src/levels';
import { SOLUTIONS } from '../src/levels/solutions';
import { ATTRIBUTES, ROOMS, SKILLS } from '../src/meta/progression';
import { DOLLARS_PER_CATNIP, fenceRate, playerLevel, xpForLevel } from '../src/meta/profile';

/** Par: generous for a player who can't see the guards' whole plan. Twice the solver's turns, and at least ten more. */
export function parFor(turns: number): number {
  return Math.max(turns + 10, Math.ceil(turns * 2));
}

const rows: string[] = [];
let xp = 0;
let catnip = 0;
for (const def of ALL_LEVELS) {
  const route = SOLUTIONS[def.id];
  const turns = route.length;
  const par = parFor(turns);
  const loot = def.loot.reduce((n, l) => n + l.value, 0);
  const centre = def.loot.find((l) => def.map[l.at.y][l.at.x] === 'G');
  // One flawless first clear with the centrepiece and the rest of the loot, at par minus a third.
  const heistXp = (def.xp ?? 100) + 50 + 50 + 100 + Math.floor(loot / 200) + Math.max(0, Math.round(par / 3)) * 5;
  xp += heistXp;
  catnip += Math.round((loot / DOLLARS_PER_CATNIP) * fenceRate(playerLevel(xp)));
  rows.push(`| ${def.name} | ${turns} | ${def.par ?? '–'} | ${par} | ${def.xp ?? 100} | $${loot.toLocaleString('en-US')} | ${centre ? `$${centre.value.toLocaleString('en-US')}` : '–'} | ${playerLevel(xp)} |`);
}

const skills = SKILLS.reduce((n, s) => n + s.cost, 0);
const rooms = ROOMS.reduce((n, r) => n + r.tiers.reduce((m, t) => m + t.cost, 0), 0);
const attributes = ATTRIBUTES.reduce((n, a) => n + a.ranks.reduce((m, _r, i) => m + 150 * (i + 1), 0), 0);
const report = `# Balance report

Generated by \`npm run balance\` from the solver's flawless routes (\`src/levels/solutions.ts\`).

**Par** is the turn count under which a heist earns the "Quick work" bonus (5 XP a turn under). It's set
to twice the solver's flawless route, and at least ten turns more: the solver sees every guard's whole
plan, and a player only sees a turn or two ahead.

| Level | Solver turns | Par was | Par now | Base XP | Loot | Centrepiece | Leo's level after |
| --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

**One flawless run through the story** (every level once, every piece of loot, a third of par to spare):
${xp.toLocaleString('en-US')} XP, which is level ${playerLevel(xp)} (level 22, for Second Wind, needs ${xpForLevel(22).toLocaleString('en-US')} XP),
and about ${catnip.toLocaleString('en-US')} Catnip from the fences before demand bonuses and the Fence's Office.

Against that: every skill costs ${skills.toLocaleString('en-US')} Catnip, every lair room at its top tier
${rooms.toLocaleString('en-US')}, and every attribute rank about ${attributes.toLocaleString('en-US')} before the Scratching Tower's
discount, ${(skills + rooms + attributes).toLocaleString('en-US')} in all. ${
  catnip >= skills + rooms + attributes
    ? 'A flawless run that takes everything earns more than all of it costs; a real first run takes less loot and is seldom flawless, so it buys most of it, and the rest comes from replays.'
    : 'A first run can’t buy everything: replays (hot loot sells at half price), demand bonuses and the collector make up the difference.'
}
${
  playerLevel(xp) < 22
    ? `\nSecond Wind needs level 22, so it's a post-game skill: about ${Math.ceil((xpForLevel(22) - xp) / 500)} more heists' worth of XP after the story.\n`
    : ''
}`;

console.log(report);
writeFileSync('docs/BALANCE.md', report);

if (process.argv.includes('--apply')) {
  const files = ['tutorial', 'oldtown', 'museummile', 'heights', 'harbour', 'downtown', 'midnight', 'prototype'].map((f) => `src/levels/${f}.ts`);
  for (const f of files) {
    let text = readFileSync(f, 'utf8');
    for (const def of ALL_LEVELS) {
      const at = text.indexOf(`id: '${def.id}'`);
      if (at < 0) continue;
      const next = text.indexOf('export const', at);
      const end = next < 0 ? text.length : next;
      const block = text.slice(at, end);
      const par = parFor(SOLUTIONS[def.id].length);
      const updated = /\n  par: \d+,/.test(block) ? block.replace(/\n  par: \d+,/, `\n  par: ${par},`) : block.replace(/\n  xp: (\d+),/, `\n  xp: $1,\n  par: ${par},`);
      text = text.slice(0, at) + updated + text.slice(end);
    }
    writeFileSync(f, text);
  }
  console.log('Par updated in the level files.');
}
